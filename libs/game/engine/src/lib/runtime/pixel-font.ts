/** Parsed glyph bitmaps keyed by character. */
export const GLYPHS: ReadonlyMap<string, readonly string[]> = new Map(
  GLYPH_SOURCE.map(([ch, rows]) => [ch, rows.split('|')]),
);

/** Glyph rows for a character; lowercase maps to uppercase and unknown characters to `?`. */
export function glyphFor(ch: string): readonly string[] {
  return GLYPHS.get(ch.toUpperCase()) ?? GLYPHS.get('?') ?? [];
}

/** Width in pixels of a string rendered with this font. */
export function textWidth(text: string): number {
  return text.length * CELL_WIDTH;
}

/**
 * Splits text into lines that fit within `maxChars` characters, breaking on spaces.
 */
export function wrapText(text: string, maxChars: number): string[] {
  const lines: string[] = [];
  for (const paragraph of text.split('\n')) {
    let line = '';
    for (const word of paragraph.split(' ')) {
      const candidate = line ? `${line} ${word}` : word;
      if (candidate.length <= maxChars) {
        line = candidate;
      } else {
        if (line) {
          lines.push(line);
        }
        line = word.length > maxChars ? word.slice(0, maxChars) : word;
      }
    }
    lines.push(line);
  }
  return lines;
}
